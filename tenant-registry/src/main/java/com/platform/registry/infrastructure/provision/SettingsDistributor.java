package com.platform.registry.infrastructure.provision;

import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Component;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.Statement;
import java.util.Map;

/**
 * After pack seed on People, write owned settings slices into Leave / Time&amp;Work
 * and slim People {@code tenant_settings} so DBs no longer share one JSON blob.
 */
@Component
public class SettingsDistributor {

    private static final Logger log = LoggerFactory.getLogger(SettingsDistributor.class);

    private final ObjectMapper objectMapper;

    public SettingsDistributor(ObjectMapper objectMapper) {
        this.objectMapper = objectMapper;
    }

    public void distributeOwnedSlices(
            String peopleJdbc,
            String leaveJdbc,
            String timeWorkJdbc,
            String username,
            String password) {
        try {
            Map<String, Object> full = readSettings(peopleJdbc, username, password, "tenant_settings");
            if (full.isEmpty()) {
                log.info("No People tenant_settings to split");
                return;
            }
            Map<String, Object> peopleSlice = SettingsOwnership.slicePeople(full);
            Map<String, Object> leaveSlice = SettingsOwnership.sliceLeave(full);
            Map<String, Object> timeWorkSlice = SettingsOwnership.sliceTimeWork(full);

            upsertSettings(peopleJdbc, username, password, "tenant_settings", peopleSlice);
            upsertSettings(leaveJdbc, username, password, "leave_settings", leaveSlice);
            upsertSettings(timeWorkJdbc, username, password, "timework_settings", timeWorkSlice);

            log.info("Distributed settings slices peopleKeys={} leaveKeys={} timeworkKeys={}",
                    peopleSlice.keySet(), leaveSlice.keySet(), timeWorkSlice.keySet());
        } catch (Exception e) {
            throw new IllegalStateException("Failed distributing settings ownership: " + e.getMessage(), e);
        }
    }

    private Map<String, Object> readSettings(String jdbc, String user, String pass, String table) throws Exception {
        try (Connection conn = DriverManager.getConnection(jdbc, user, pass);
             Statement st = conn.createStatement();
             ResultSet rs = st.executeQuery(
                     "SELECT settings::text FROM \"" + table + "\" ORDER BY id LIMIT 1")) {
            if (!rs.next()) {
                return Map.of();
            }
            String json = rs.getString(1);
            if (json == null || json.isBlank()) {
                return Map.of();
            }
            return objectMapper.readValue(json, new TypeReference<>() {});
        } catch (Exception tableMissing) {
            // Table may not exist yet on a half-migrated DB.
            log.debug("readSettings skip {}: {}", table, tableMissing.getMessage());
            return Map.of();
        }
    }

    private void upsertSettings(
            String jdbc,
            String user,
            String pass,
            String table,
            Map<String, Object> settings) throws Exception {
        String json = objectMapper.writeValueAsString(settings == null ? Map.of() : settings);
        try (Connection conn = DriverManager.getConnection(jdbc, user, pass)) {
            conn.setAutoCommit(false);
            ensureTable(conn, table);
            try (Statement st = conn.createStatement();
                 ResultSet rs = st.executeQuery("SELECT id FROM \"" + table + "\" ORDER BY id LIMIT 1")) {
                if (rs.next()) {
                    long id = rs.getLong(1);
                    try (PreparedStatement ps = conn.prepareStatement(
                            "UPDATE \"" + table + "\" SET settings = ?::jsonb, updated_at = NOW() WHERE id = ?")) {
                        ps.setString(1, json);
                        ps.setLong(2, id);
                        ps.executeUpdate();
                    }
                } else {
                    try (PreparedStatement ps = conn.prepareStatement(
                            "INSERT INTO \"" + table + "\" (settings, updated_at) VALUES (?::jsonb, NOW())")) {
                        ps.setString(1, json);
                        ps.executeUpdate();
                    }
                }
            }
            conn.commit();
        }
    }

    private static void ensureTable(Connection conn, String table) throws Exception {
        try (Statement st = conn.createStatement()) {
            st.execute("""
                    CREATE TABLE IF NOT EXISTS "%s" (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      settings JSONB NOT NULL,
                      updated_at TIMESTAMPTZ NOT NULL
                    )
                    """.formatted(table));
        }
    }
}
